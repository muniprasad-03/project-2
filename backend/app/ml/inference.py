RIASEC_TYPES = (
    "Realistic",
    "Investigative",
    "Artistic",
    "Social",
    "Enterprising",
    "Conventional",
)


# ---------------------------------------------------------------------------
# Artifact loading
# ---------------------------------------------------------------------------

def _check_artifacts() -> None:
    """
    Verify that all artifacts generated by train.py exist.
    """
    required_files = (
        TFIDF_PATH,
        MATRIX_PATH,
        METADATA_PATH,
    )

    missing = [
        str(path)
        for path in required_files
        if not path.exists()
    ]

    if missing:
        raise FileNotFoundError(
            "Required ML artifacts are missing:\n"
            + "\n".join(missing)
            + "\n\nRun preprocessing and training first."
        )


def _load_artifacts():
    """
    Load the trained ML artifacts.

    This function is called once when the module is imported.
    """
    _check_artifacts()

    logger.info("Loading ML artifacts...")

    vectorizer = joblib.load(TFIDF_PATH)

    occupation_matrix = joblib.load(MATRIX_PATH)

    import json

    with open(
        METADATA_PATH,
        "r",
        encoding="utf-8",
    ) as file:
        metadata = json.load(file)

    occupation_order = metadata.get(
        "occupation_order",
        [],
    )

    occupations = metadata.get(
        "occupations",
        {},
    )

    if not occupation_order:
        raise ValueError(
            "occupation_metadata.json contains no occupation order."
        )

    if not occupations:
        raise ValueError(
            "occupation_metadata.json contains no occupations."
        )

    if occupation_matrix.shape[0] != len(occupation_order):
        raise ValueError(
            "Occupation matrix row count does not match "
            "occupation metadata."
        )

    logger.info(
        "Loaded %d occupations",
        len(occupation_order),
    )

    logger.info(
        "TF-IDF vocabulary size: %d",
        len(vectorizer.vocabulary_),
    )

    logger.info(
        "Occupation matrix shape: %s",
        occupation_matrix.shape,
    )

    return (
        vectorizer,
        occupation_matrix,
        metadata,
    )


