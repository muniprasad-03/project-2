ARTIFACTS_DIR = PROJECT_ROOT / "data" / "artifacts"

TFIDF_PATH = ARTIFACTS_DIR / "tfidf_vectorizer.pkl"
MATRIX_PATH = ARTIFACTS_DIR / "occupation_matrix.pkl"
METADATA_PATH = ARTIFACTS_DIR / "occupation_metadata.json"


